export function everyLabel(sec: number): string {
  if (sec < 60) return `раз в ${sec} с`;
  if (sec < 3600) return `раз в ${Math.round(sec / 60)} мин`;
  return `раз в ${Math.round(sec / 3600)} ч`;
}

export function plural(n: number, one: string, few: string, many: string): string {
  const rule = new Intl.PluralRules("ru-RU").select(n);
  if (rule === "one") return one;
  if (rule === "few") return few;
  return many;
}
